-- V27: «теневые» блокировки вместо пропуска эха по датам.
--
-- В V26 событие канала, совпавшее по датам со свежей ручной записью, считалось её
-- эхом и не импортировалось. Но совпадение дат — догадка: это может быть и настоящая
-- бронь с площадки. Тогда после удаления ручной записи даты у нас освобождались,
-- а на площадке бронь оставалась — овербукинг.
--
-- Теперь такое событие импортируется обычной блокировкой канала с пометкой
-- shadow_of_manual_id. Пока ручная запись жива, тень не показывается и не считается
-- (иначе двойная занятость и ложный конфликт); когда ручную запись удаляют, тень
-- остаётся и держит даты закрытыми, пока событие есть в фиде площадки.
--
-- ON DELETE SET NULL: через 30 дней удалённая ручная запись стирается физически,
-- тень при этом становится обычной блокировкой канала.

ALTER TABLE calendar_blocks
    ADD COLUMN IF NOT EXISTS shadow_of_manual_id BIGINT
        REFERENCES calendar_blocks(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_calendar_blocks_shadow
    ON calendar_blocks(shadow_of_manual_id) WHERE shadow_of_manual_id IS NOT NULL;
