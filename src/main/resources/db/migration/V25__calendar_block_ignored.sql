-- V25: «открыть даты», закрытые площадкой.
-- Блокировку, импортированную с канала, нельзя просто удалить: при следующей
-- синхронизации она вернётся из фида. Поэтому хост помечает её ignored — строка
-- остаётся (синхронизация узнаёт её по external_uid и не создаёт заново), но
-- занятостью не считается: день свободен в шахматке и не уходит в экспорт.
-- Когда событие исчезнет из фида площадки, строка удалится обычным порядком.

ALTER TABLE calendar_blocks
    ADD COLUMN IF NOT EXISTS ignored BOOLEAN NOT NULL DEFAULT FALSE;
