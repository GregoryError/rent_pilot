package ru.rentoptima.service;

/**
 * Причины отказа публичного API виджета. Клиент показывает текст на языке гостя по
 * коду; {@code message} — русский текст по умолчанию (и для прежнего виджета, который
 * кодов не знает). {@code %d} в тексте — параметр из настроек виджета.
 */
public enum WidgetError {
    DATES_REQUIRED("Выберите даты заезда и выезда"),
    DATES_ORDER("Дата выезда должна быть позже даты заезда"),
    DATE_PAST("Дата заезда уже прошла"),
    WINDOW("Бронирование открыто не дальше чем на %d дн. вперёд"),
    MIN_NIGHTS("Минимальный срок — %d ноч."),
    MAX_NIGHTS("Максимальный срок — %d ноч."),
    NO_CHECKIN_DAY("В этот день недели заезд не принимается"),
    NO_CHECKOUT_DAY("В этот день недели выезд не принимается"),
    DATES_TAKEN("Эти даты только что заняли. Выберите другие"),
    UNAVAILABLE("Бронирование временно недоступно"),
    GUESTS("Число гостей — от 1 до %d"),
    PETS_NOT_ALLOWED("С питомцами здесь не принимают"),
    NAME("Укажите, как к вам обращаться"),
    PHONE("Укажите телефон для связи"),
    EMAIL("Проверьте адрес электронной почты"),
    CONSENT("Нужно согласие на обработку контактных данных"),
    PROMO_INVALID("Такого промокода нет"),
    PROMO_EXPIRED("Срок действия промокода истёк"),
    PROMO_EXHAUSTED("Промокод больше не действует: лимит применений исчерпан"),
    PRICE_CHANGED("Стоимость изменилась. Проверьте сумму и отправьте ещё раз"),
    TOO_FAST("Форма отправлена слишком быстро. Попробуйте ещё раз через несколько секунд"),
    FORM_EXPIRED("Страница открыта слишком давно. Выберите даты заново"),
    RATE_LIMIT("Слишком много заявок. Попробуйте позже"),
    NOT_FOUND("Бронь не найдена");

    private final String message;

    WidgetError(String message) {
        this.message = message;
    }

    public String message(Object... params) {
        return message.contains("%d") ? message.formatted(params) : message;
    }
}
